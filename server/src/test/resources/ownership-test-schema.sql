CREATE TABLE IF NOT EXISTS address (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,user_id BIGINT,receiver_name VARCHAR(50),receiver_phone VARCHAR(20),
 province VARCHAR(50),city VARCHAR(50),district VARCHAR(50),detail VARCHAR(255),is_default INT DEFAULT 0,
 create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS product_comment (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,user_id BIGINT,product_id BIGINT,order_id BIGINT,rating INT,
 content VARCHAR(500),pics VARCHAR(1000),append_content VARCHAR(500),append_time TIMESTAMP,
 create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS product_collect (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,user_id BIGINT,product_id BIGINT,create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,product_id)
);
